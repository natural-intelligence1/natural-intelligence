// ─── packages/db/src/protocols/versionItems.ts ──────────────────────────────
// The clinical content of a Protocol version, and the rules governing it.
//
// A Protocol version owns its items. A template is only where a draft may
// have started. That distinction is the whole point: before this existed, a
// client's "Protocol" was a pointer at a shared template, so no practitioner
// could edit one client's plan and no signature could freeze anything.
//
// Enforcement lives in the database (0061). This module is the safe write
// path and the pure rules that callers — and tests — can rely on without one.

import type { SupabaseClient } from '@supabase/supabase-js'

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyClient = SupabaseClient<any>

/** How a draft item reached the practitioner. Audit only — it never dilutes
 *  the professional status of the signed Protocol. */
export const DRAFTING_SOURCES = [
  'ni_tooling',   // generated by NI tooling
  'ai_assisted',  // produced through an AI-assisted workflow
  'student',      // drafted by a supervised student
  'practitioner', // written by a practitioner directly
  'template',     // copied from a published protocol template
] as const
export type DraftingSource = (typeof DRAFTING_SOURCES)[number]

export const ITEM_TYPES = ['supplement', 'lifestyle', 'nutrition', 'test', 'practitioner'] as const
export type ProtocolItemType = (typeof ITEM_TYPES)[number]

/** Everything a practitioner may author. If a field is clinically
 *  substantive it belongs here, because the governing test is whether the
 *  practitioner could make the Protocol exactly what they would have written
 *  themselves. */
export interface ProtocolVersionItemInput {
  name: string
  item_type: ProtocolItemType
  dose?: string | null
  timing?: string | null
  duration_weeks?: number | null
  instructions?: string | null
  rationale?: string | null
  display_order?: number
  is_active?: boolean
}

export interface ProtocolVersionItem extends ProtocolVersionItemInput {
  id: string
  protocol_id: string
  display_order: number
  is_active: boolean
  source_template_item_id: string | null
  drafted_source: DraftingSource
  drafted_by: string | null
  last_edited_by: string | null
  created_at: string
  updated_at: string
}

/** The signing-relevant shape of a Protocol version. */
export interface ProtocolVersionRef {
  id: string
  version: number
  signed_at: string | null
  signed_by: string | null
  supersedes: string | null
  member_id?: string
  case_id?: string | null
}

// ── Pure rules ──────────────────────────────────────────────────────────────

export const ITEM_VALIDATION_MESSAGES = {
  name_blank: 'Every Protocol item needs a name.',
  item_type_unknown: `item_type must be one of: ${ITEM_TYPES.join(', ')}.`,
  duration_not_positive: 'duration_weeks must be a positive number of weeks, or left empty.',
} as const

/** Validate practitioner-authored content before it reaches the database.
 *  Returns every problem, not just the first — a practitioner editing a plan
 *  should see all of them at once. */
export function validateItemInput(input: ProtocolVersionItemInput): string[] {
  const problems: string[] = []
  if (!input.name || input.name.trim().length === 0) problems.push(ITEM_VALIDATION_MESSAGES.name_blank)
  if (!(ITEM_TYPES as readonly string[]).includes(input.item_type)) problems.push(ITEM_VALIDATION_MESSAGES.item_type_unknown)
  if (input.duration_weeks != null && !(Number.isInteger(input.duration_weeks) && input.duration_weeks > 0)) {
    problems.push(ITEM_VALIDATION_MESSAGES.duration_not_positive)
  }
  return problems
}

/** A Protocol version is editable only while it carries no signature. */
export function isEditable(protocol: ProtocolVersionRef): boolean {
  return protocol.signed_at === null
}

/**
 * May this Protocol version be the source DailyPath derives actions from?
 *
 * Only a signed version, and only the one nothing supersedes. An unsigned
 * draft has no clinical status whatever its provenance, and a superseded
 * version is history.
 */
export function isDailyPathEligible(
  protocol: ProtocolVersionRef,
  allVersions: readonly ProtocolVersionRef[] = [],
): boolean {
  if (protocol.signed_at === null) return false
  return !allVersions.some((v) => v.supersedes === protocol.id)
}

/** The current signed Protocol for a member, or null if they have none.
 *  Null is a legitimate state: "no signed Protocol yet" is what the client
 *  sees before their practitioner signs one. */
export function selectDailyPathSource(
  versions: readonly ProtocolVersionRef[],
): ProtocolVersionRef | null {
  const eligible = versions.filter((v) => isDailyPathEligible(v, versions))
  if (eligible.length === 0) return null
  return eligible.reduce((a, b) => (b.version > a.version ? b : a))
}

export class ProtocolNotSignedError extends Error {
  readonly code = 'protocol_not_signed'
  constructor(protocolId: string, version: number) {
    super(
      `Protocol ${protocolId} (v${version}) is an unsigned draft. A draft has no clinical status: ` +
      'it cannot be shown to the client as their plan and cannot be a DailyPath source. ' +
      'It must be reviewed and signed by the responsible practitioner first.',
    )
    this.name = 'ProtocolNotSignedError'
  }
}

export class ProtocolSignedError extends Error {
  readonly code = 'protocol_signed'
  constructor(protocolId: string, version: number) {
    super(
      `Protocol ${protocolId} (v${version}) is signed and is the practitioner's professional work. ` +
      'A signed version cannot be edited — revise it to create the next draft version instead.',
    )
    this.name = 'ProtocolSignedError'
  }
}

/** Hard stop before any client-facing or DailyPath use. */
export function assertUsableAsClientProtocol(
  protocol: ProtocolVersionRef,
  allVersions: readonly ProtocolVersionRef[] = [],
): void {
  if (protocol.signed_at === null) throw new ProtocolNotSignedError(protocol.id, protocol.version)
  if (!isDailyPathEligible(protocol, allVersions)) {
    throw new Error(
      `Protocol ${protocol.id} (v${protocol.version}) has been superseded by a later signed version ` +
      'and is no longer the current Protocol.',
    )
  }
}

/** Hard stop before any edit. */
export function assertEditable(protocol: ProtocolVersionRef): void {
  if (!isEditable(protocol)) throw new ProtocolSignedError(protocol.id, protocol.version)
}

/**
 * Copy a version's items forward into the next draft. Pure, so the revision
 * rule can be tested without a database.
 *
 * Provenance is carried, not reset: an item that began life as an
 * AI-assisted suggestion three versions ago still says so. What changes is
 * that the new rows belong to the new version and are editable again.
 */
export function copyItemsForward(
  items: readonly ProtocolVersionItem[],
  newProtocolId: string,
  editor: string | null,
): Array<Omit<ProtocolVersionItem, 'id' | 'created_at' | 'updated_at'>> {
  return items
    .filter((i) => i.is_active)
    .map((i) => ({
      protocol_id: newProtocolId,
      name: i.name,
      item_type: i.item_type,
      dose: i.dose ?? null,
      timing: i.timing ?? null,
      duration_weeks: i.duration_weeks ?? null,
      instructions: i.instructions ?? null,
      rationale: i.rationale ?? null,
      display_order: i.display_order,
      is_active: true,
      source_template_item_id: i.source_template_item_id,
      drafted_source: i.drafted_source,
      drafted_by: i.drafted_by,
      last_edited_by: editor,
    }))
}

// ── Write paths ─────────────────────────────────────────────────────────────
// These are the only supported ways to change Protocol content. The database
// refuses anything that reaches a signed version regardless, but going
// through these keeps provenance and ordering coherent.

/** Seed a new draft from a published template. The template is read, never
 *  written: it is starting material, not the record. */
export async function seedDraftFromTemplate(
  client: AnyClient,
  opts: { protocolId: string; templateId: string; draftedBy: string | null; draftedSource?: DraftingSource },
): Promise<ProtocolVersionItem[]> {
  const { data: templateItems, error: readErr } = await client
    .from('protocol_items')
    .select('id, name, item_type, dose, timing, duration_weeks, notes, display_order')
    .eq('template_id', opts.templateId)
    .order('display_order', { ascending: true })
  if (readErr) throw new Error(`seedDraftFromTemplate read failed: ${readErr.message}`)

  const rows = (templateItems ?? []).map((t: Record<string, unknown>, index: number) => ({
    protocol_id: opts.protocolId,
    name: t.name as string,
    item_type: t.item_type as ProtocolItemType,
    dose: (t.dose as string | null) ?? null,
    timing: (t.timing as string | null) ?? null,
    duration_weeks: (t.duration_weeks as number | null) ?? null,
    // The template's notes are its instructions to the client; rationale is
    // the practitioner's to write.
    instructions: (t.notes as string | null) ?? null,
    rationale: null,
    display_order: (t.display_order as number | null) ?? index,
    is_active: true,
    source_template_item_id: t.id as string,
    drafted_source: opts.draftedSource ?? ('template' as DraftingSource),
    drafted_by: opts.draftedBy,
    last_edited_by: null,
  }))
  if (rows.length === 0) return []

  const { data, error } = await client.from('protocol_version_items').insert(rows as never).select('*')
  if (error) throw new Error(`seedDraftFromTemplate insert failed: ${error.message}`)
  return (data ?? []) as ProtocolVersionItem[]
}

/** Edit one item of a draft. The database refuses if the version is signed. */
export async function updateDraftItem(
  client: AnyClient,
  itemId: string,
  patch: Partial<ProtocolVersionItemInput>,
  editor: string | null,
): Promise<ProtocolVersionItem> {
  if (patch.name !== undefined || patch.item_type !== undefined || patch.duration_weeks !== undefined) {
    const problems = validateItemInput({
      name: patch.name ?? 'placeholder',
      item_type: patch.item_type ?? 'supplement',
      duration_weeks: patch.duration_weeks,
    })
    // Only report problems about fields actually being changed.
    const relevant = problems.filter((p) =>
      (patch.name !== undefined && p === ITEM_VALIDATION_MESSAGES.name_blank) ||
      (patch.item_type !== undefined && p === ITEM_VALIDATION_MESSAGES.item_type_unknown) ||
      (patch.duration_weeks !== undefined && p === ITEM_VALIDATION_MESSAGES.duration_not_positive))
    if (relevant.length > 0) throw new Error(relevant.join(' '))
  }

  const { data, error } = await client
    .from('protocol_version_items')
    .update({ ...patch, last_edited_by: editor } as never)
    .eq('id', itemId)
    .select('*')
    .single()
  if (error) throw new Error(`updateDraftItem failed [${error.code}]: ${error.message}`)
  return data as ProtocolVersionItem
}

/**
 * Revise a signed Protocol: create the next version as an unsigned draft with
 * the previous version's items copied forward, leaving the signed predecessor
 * exactly as it was.
 *
 * This is the only route to changing a signed Protocol, which is why there is
 * no "edit signed version" path anywhere in this module.
 */
export async function reviseProtocol(
  client: AnyClient,
  signedProtocolId: string,
  editor: string | null,
): Promise<{ draft: ProtocolVersionRef; items: ProtocolVersionItem[] }> {
  const { data: prev, error: prevErr } = await client
    .from('member_protocols')
    .select('id, member_id, case_id, template_id, name, version, signed_at, signed_by, supersedes, started_at, notes')
    .eq('id', signedProtocolId)
    .single()
  if (prevErr || !prev) throw new Error(`reviseProtocol: protocol not found: ${prevErr?.message ?? signedProtocolId}`)

  const previous = prev as Record<string, unknown>
  if (previous.signed_at === null) {
    throw new Error(
      `Protocol ${signedProtocolId} (v${previous.version}) is already an unsigned draft. ` +
      'Edit it directly rather than revising it.',
    )
  }

  const { data: created, error: createErr } = await client
    .from('member_protocols')
    .insert({
      member_id: previous.member_id,
      case_id: previous.case_id,
      template_id: previous.template_id,
      name: previous.name,
      version: (previous.version as number) + 1,
      supersedes: signedProtocolId,
      notes: previous.notes,
    } as never)
    .select('id, version, signed_at, signed_by, supersedes, member_id, case_id')
    .single()
  if (createErr || !created) throw new Error(`reviseProtocol: could not create draft: ${createErr?.message}`)
  const draft = created as unknown as ProtocolVersionRef

  const { data: prevItems, error: itemsErr } = await client
    .from('protocol_version_items')
    .select('*')
    .eq('protocol_id', signedProtocolId)
    .order('display_order', { ascending: true })
  if (itemsErr) throw new Error(`reviseProtocol: could not read previous items: ${itemsErr.message}`)

  const forward = copyItemsForward((prevItems ?? []) as ProtocolVersionItem[], draft.id, editor)
  if (forward.length === 0) return { draft, items: [] }

  const { data: copied, error: copyErr } = await client
    .from('protocol_version_items').insert(forward as never).select('*')
  if (copyErr) throw new Error(`reviseProtocol: could not copy items forward: ${copyErr.message}`)

  return { draft, items: (copied ?? []) as ProtocolVersionItem[] }
}

/** Read the items a client or DailyPath may use. Refuses unsigned drafts and
 *  superseded versions before any content is returned. */
export async function getSignedProtocolItems(
  client: AnyClient,
  protocolId: string,
): Promise<{ protocol: ProtocolVersionRef; items: ProtocolVersionItem[] }> {
  const { data: p, error: pErr } = await client
    .from('member_protocols')
    .select('id, member_id, case_id, version, signed_at, signed_by, supersedes')
    .eq('id', protocolId)
    .single()
  if (pErr || !p) throw new Error(`getSignedProtocolItems: protocol not found: ${pErr?.message ?? protocolId}`)
  const protocol = p as unknown as ProtocolVersionRef

  const { data: siblings } = await client
    .from('member_protocols')
    .select('id, version, signed_at, signed_by, supersedes')
    .eq('member_id', (p as Record<string, unknown>).member_id as string)

  assertUsableAsClientProtocol(protocol, (siblings ?? []) as unknown as ProtocolVersionRef[])

  const { data: items, error: iErr } = await client
    .from('protocol_version_items')
    .select('*')
    .eq('protocol_id', protocolId)
    .eq('is_active', true)
    .order('display_order', { ascending: true })
  if (iErr) throw new Error(`getSignedProtocolItems: could not read items: ${iErr.message}`)

  return { protocol, items: (items ?? []) as ProtocolVersionItem[] }
}
